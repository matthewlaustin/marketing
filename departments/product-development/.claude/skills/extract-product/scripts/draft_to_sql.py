#!/usr/bin/env python3
"""Turn a validated draft record into SQL that loads it as a draft product.

Usage: python3 -I draft_to_sql.py <record.json> > <record.sql>

The SQL is applied to Neon by the database session, on a branch first (database/README.md).
It inserts the manufacturer and brand if missing, the product as draft (refusing to overwrite an
existing product with the same brand and MPN), every spec with its source, media, accessory
links as draft products, and proposed fields. Run validate_record.py first.
"""
import json, sys

def q(v):
    if v is None: return "null"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return repr(v)
    return "'" + str(v).replace("'", "''") + "'"

def jq(v): return q(json.dumps(v)) + "::jsonb"

def main():
    if len(sys.argv) != 2: print(__doc__); sys.exit(2)
    r = json.load(open(sys.argv[1]))
    m, b, p = r["manufacturer"], r["brand"], r["product"]
    out = []
    w = out.append
    w("-- Generated by extract-product from " + sys.argv[1])
    w("begin;")
    w(f"insert into manufacturers (name, slug, website) values ({q(m['name'])}, {q(m['slug'])}, {q(m.get('website'))}) on conflict (slug) do nothing;")
    w(f"insert into brands (manufacturer_id, name, slug, website) select id, {q(b['name'])}, {q(b['slug'])}, {q(b.get('website'))} from manufacturers where slug = {q(m['slug'])} on conflict (slug) do nothing;")
    w("do $$")
    w("declare v_brand uuid; v_type uuid; v_product uuid; v_media uuid; v_linked uuid;")
    w("begin")
    w(f"  select id into v_brand from brands where slug = {q(b['slug'])};")
    w(f"  select id into v_type from product_types where slug = {q(p['product_type'])} and status = 'approved';")
    w(f"  if v_type is null then raise exception 'product type % is not approved', {q(p['product_type'])}; end if;")
    w(f"  if exists (select 1 from products where brand_id = v_brand and mpn = {q(p['mpn'])}) then raise exception 'product % already exists for brand %; this load does not overwrite', {q(p['mpn'])}, {q(b['slug'])}; end if;")
    cols = ["brand_id", "product_type_id", "mpn", "title", "short_description", "long_description", "warranty_years", "warranty_type", "warranty_conditions", "warranty_component_terms", "status"]
    vals = ["v_brand", "v_type", q(p["mpn"]), q(p.get("title")), q(p.get("short_description")), q(p.get("long_description")), q(p.get("warranty_years")), q(p.get("warranty_type")), q(p.get("warranty_conditions")), q(p.get("warranty_component_terms")), "'draft'"]
    w(f"  insert into products ({', '.join(cols)}) values ({', '.join(vals)}) returning id into v_product;")
    for md in r.get("media") or []:
        w(f"  insert into product_media (product_id, kind, url, title, alt_text, sort_order, source_url) values (v_product, {q(md['kind'])}, {q(md['url'])}, {q(md.get('title'))}, {q(md.get('alt_text'))}, {q(md.get('sort_order', 0))}, {q(md.get('source_url'))});")
    for s in r.get("specs") or []:
        v = s["value"]
        col = "value_list" if isinstance(v, list) else "value_number" if isinstance(v, (int, float)) and not isinstance(v, bool) else "value_boolean" if isinstance(v, bool) else "value_text"
        val = jq(v) if isinstance(v, list) else q(v)
        notes = s.get("notes") or ""
        if s.get("quote"): notes = (notes + "\n" if notes else "") + "Source says: " + s["quote"]
        w(f"  insert into product_specs (product_id, spec_field_id, {col}, source_url, extracted_at, extracted_by, notes) select v_product, sf.id, {val}, {q(s['source_url'])}, {q(s.get('extracted_at'))}::timestamptz, {q(s.get('extracted_by', 'claude'))}, {q(notes or None)} from spec_fields sf where sf.product_type_id = v_type and sf.key = {q(s['key'])};")
    for l in r.get("linked_products") or []:
        lp = l["linked_product"]
        w(f"  insert into products (brand_id, product_type_id, mpn, title, status) select id, v_type, {q(lp['mpn'])}, {q(lp.get('title'))}, 'draft' from brands where slug = {q(lp['brand'])} on conflict (brand_id, mpn) do nothing;")
        w(f"  select pr.id into v_linked from products pr join brands br on br.id = pr.brand_id where br.slug = {q(lp['brand'])} and pr.mpn = {q(lp['mpn'])};")
        w(f"  insert into product_links (product_id, linked_product_id, kind, source_url, notes) values (v_product, v_linked, {q(l['kind'])}, {q(l.get('source_url'))}, {q(l.get('notes'))}) on conflict do nothing;")
    for pf in r.get("proposed_spec_fields") or []:
        w(f"  insert into proposed_spec_fields (product_type_id, product_id, suggested_key, suggested_label, example_value, source_url, rationale) values (v_type, v_product, {q(pf['suggested_key'])}, {q(pf.get('suggested_label'))}, {q(pf.get('example_value'))}, {q(pf.get('source_url'))}, {q(pf.get('rationale'))});")
    w("end $$;")
    w("commit;")
    print("\n".join(out))

if __name__ == "__main__":
    main()
